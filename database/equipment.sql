-- Run once against biomedical_maintenance. Existing tables are left untouched.
CREATE TABLE IF NOT EXISTS equipment (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL CHECK (length(trim(name)) > 0),
    type VARCHAR(255) NOT NULL CHECK (length(trim(type)) > 0),
    location VARCHAR(255) NOT NULL CHECK (length(trim(location)) > 0),
    status VARCHAR(32) NOT NULL CHECK (status IN ('Operational', 'Under Maintenance', 'Inactive'))
);
